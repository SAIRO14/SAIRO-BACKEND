-- 코스에 소유자를 준다. (ADR 0012, 이슈 #49)
--
-- 지금까지 courses에는 소유자가 없어 courseId를 아는 사람은 누구나 그 코스를
-- 공유하거나 저장할 수 있었다. "소유자 조건 없는 조회 쿼리를 만들지 않는다"(AGENTS.md §1)와
-- 어긋나 있었고, 저장 목록(#31)이 코스 내용을 반환하기 시작하면 노출 범위가 커진다.

-- NULL을 허용한다. 이 컬럼이 생기기 전에 만들어진 행에는 소유자가 없기 때문이다.
-- 소유자 조건이 붙은 조회는 device_id = ? 로 판정하므로 옛 행은 자연히 걸리지 않는다.
-- 출시 전이라 대상 행이 사실상 없어 백필하지 않는다. shared_courses.course_id와 같은 판단이다.
ALTER TABLE courses
    ADD COLUMN IF NOT EXISTS device_id TEXT;

-- 코스 조회는 항상 course_id(PK)로 한 행을 집은 뒤 소유자를 확인한다.
-- 별도 인덱스를 만들지 않는 이유다. "내가 만든 코스 목록"이 생기면 그때 추가한다.

-- 참고: V3의 saved_trips.device_id 주석에 있는 "courses에는 소유자가 없다"는
-- 이 마이그레이션 이전 상태를 가리킨다. 적용된 마이그레이션은 고치지 않으므로 그대로 둔다.
-- 두 device_id의 현재 관계는 docs/data-model.md에 있다.
